#!/usr/bin/env python3
"""Regenerate content and run every host-side C and Python regression test."""
import argparse
import os
from pathlib import Path
import shlex
import subprocess
import sys
import tempfile


def run(command, root):
    """Execute a tool with live output and propagate build failures."""
    subprocess.run(command, cwd=root, check=True)


def main():
    """Build shared host objects once, then report all independent test failures."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-content", action="store_true",
                        help="use content already regenerated by the CMake dependency")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if not args.skip_content:
        run([sys.executable, "tools/content_compiler/compile_content.py",
             "--project-root", str(root)], root)
    compiler = shlex.split(os.environ.get("CC", "cc"))
    flags = ["-std=c11", "-UNDEBUG", "-Isrc", "-Igenerated"]
    sources = ["src/engine/world.c", "src/engine/achievements.c", "src/engine/savegame.c",
               "src/ui/achievements.c", "src/ui/notice.c", "src/ui/text_layout.c",
               "src/ui/virtual_keyboard.c", "generated/content_data.c", "generated/content_scene_data.c"]
    failures = []
    with tempfile.TemporaryDirectory(prefix="wastesedge-tests-") as directory:
        temporary = Path(directory)
        objects = []
        print("Building host regression tests", flush=True)
        for source in sources:
            output = temporary / (source.replace("/", "_") + ".o")
            run(compiler + flags + ["-c", source, "-o", str(output)], root)
            objects.append(str(output))
        for test in sorted((root / "tools").glob("test_*.c")):
            print(f"Running {test.name}", flush=True)
            executable = temporary / test.stem
            try:
                run(compiler + flags + [str(test)] + objects + ["-o", str(executable)], root)
                run([str(executable)], root)
            except subprocess.CalledProcessError:
                failures.append(test.name)
        print("Running Python regression tests", flush=True)
        try:
            run([sys.executable, "-m", "unittest", "discover", "-s", "tools", "-p", "test_*.py", "-v"], root)
        except subprocess.CalledProcessError:
            failures.append("Python tests")
    if failures:
        print("Failed: " + ", ".join(failures), file=sys.stderr)
        return 1
    print("All host regression tests passed", flush=True)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"Host regression build failed: {error}", file=sys.stderr)
        sys.exit(1)
